// Plain text of every published page, for llms-full.txt.
export function writingText(site, w) {
  return w.pages.map((p) => {
    const head = p.kind === 'part' ? `### ${p.series.title}, part ${p.n}: ${p.title}` : `### ${p.title}`;
    return `${head}\n\n${site + p.path}${p.date ? ` · ${p.date}` : ''}\n\n${p.description}\n\n${p.text}\n`;
  }).join('\n');
}
