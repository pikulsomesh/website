/* ---------- Structured data ---------- */
const author = (site) => ({ '@type': 'Person', '@id': `${site}#person`, name: 'Somesh Mohapatra', url: site });
const crumbList = (site, items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: [{ name: 'Home', path: '' }, { name: 'Writing', path: 'writing/' }, ...items].map((c, i) => ({ '@type': 'ListItem', position: i + 1, name: c.name, item: site + c.path })),
});
const abs = (site, u) => (u.startsWith('http') ? u : site + u.replace(/^\//, ''));
const imageUrl = (site, p) => { const u = [p.image, p.series?.image].find((x) => x && !x.endsWith('.svg')); return u ? abs(site, u) : `${site}assets/img/og.jpg`; };
// The hero first, then every figure in the text, so image search can find the diagrams.
const imageList = (site, p) => [...new Set([imageUrl(site, p), ...(p.images || []).map((u) => abs(site, u))])];
const code = (site, s) => (s.repo ? { '@type': 'SoftwareSourceCode', name: s.title, codeRepository: s.repo, ...(s.live ? { url: s.live } : {}), author: { '@id': `${site}#person` } } : null);

function articleLD(site, p) {
  const s = p.series;
  const crumbs = s ? [{ name: s.title, path: s.path }, { name: p.title, path: p.path }] : [{ name: p.title, path: p.path }];
  const repo = s ? s.repo : p.repo;
  return {
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'WebPage', '@id': `${site + p.path}#webpage`, url: site + p.path, name: p.title, isPartOf: { '@id': `${site}#website` }, inLanguage: 'en', breadcrumb: { '@id': `${site + p.path}#breadcrumb` } },
      {
        '@type': s ? 'TechArticle' : 'BlogPosting',
        '@id': `${site + p.path}#article`,
        headline: p.title,
        description: p.description,
        image: imageList(site, p),
        datePublished: p.date,
        dateModified: p.updated,
        author: author(site),
        publisher: { '@id': `${site}#person` },
        mainEntityOfPage: { '@id': `${site + p.path}#webpage` },
        inLanguage: 'en',
        wordCount: p.words,
        ...(p.tags.length ? { keywords: p.tags.join(', ') } : {}),
        ...(p.topic || s?.topic ? { articleSection: p.topic || s.topic } : {}),
        ...(s ? { isPartOf: { '@type': 'CreativeWorkSeries', '@id': `${site + s.path}#series`, name: s.title, url: site + s.path }, position: p.n } : {}),
        ...(repo ? { about: { '@type': 'SoftwareSourceCode', codeRepository: repo, ...(s?.live ? { url: s.live } : {}) } } : {}),
        ...(p.linkedin ? { sameAs: [p.linkedin] } : {}),
      },
      { ...crumbList(site, crumbs), '@id': `${site + p.path}#breadcrumb` },
    ],
  };
}

function seriesLD(site, s) {
  const parts = s.parts.filter((p) => p.published);
  const ld = code(site, s);
  return {
    '@context': 'https://schema.org',
    '@graph': [
      { '@type': 'CollectionPage', '@id': `${site + s.path}#webpage`, url: site + s.path, name: s.title, isPartOf: { '@id': `${site}#website` }, inLanguage: 'en', mainEntity: { '@id': `${site + s.path}#series` }, breadcrumb: { '@id': `${site + s.path}#breadcrumb` } },
      {
        '@type': 'CreativeWorkSeries',
        '@id': `${site + s.path}#series`,
        name: s.title,
        description: s.description,
        url: site + s.path,
        image: imageUrl(site, s),
        author: author(site),
        datePublished: s.date,
        dateModified: [s.updated, ...parts.map((p) => p.updated)].sort().at(-1),
        inLanguage: 'en',
        ...(s.topic ? { genre: s.topic } : {}),
        hasPart: parts.map((p) => ({ '@type': 'TechArticle', '@id': `${site + p.path}#article`, headline: p.title, url: site + p.path, position: p.n, datePublished: p.date })),
        ...(ld ? { about: ld } : {}),
        ...(s.paper ? { citation: { '@type': 'ScholarlyArticle', name: s.paper_title || s.title, url: s.paper, author: { '@id': `${site}#person` } } } : {}),
      },
      { ...crumbList(site, [{ name: s.title, path: s.path }]), '@id': `${site + s.path}#breadcrumb` },
    ],
  };
}

/* ---------- Page bodies ---------- */
const extLink = (href, label) => `<a href="${esc(href)}" target="_blank" rel="noopener">${esc(label)} ↗</a>`;
const projectLinks = (s) => [s.repo && extLink(s.repo, 'Code'), s.live && extLink(s.live, 'Live demo'), s.paper && extLink(s.paper, 'Paper')].filter(Boolean).join('');
const hero = (p) => (p.image ? `<figure class="article-hero"><img src="${esc(p.image)}" alt="${esc(p.image_alt || '')}" width="1600" height="900">${p.image_caption ? `<figcaption>${esc(p.image_caption)}</figcaption>` : ''}</figure>` : '');

function partsList(s, current) {
  return `<ol class="series-parts">${s.parts.map((p) => {
    const here = current && p.n === current.n;
    const label = `<span class="mono">Part ${p.n}</span>`;
    if (!p.published) return `<li class="is-coming">${label}<div><b>${esc(p.title)}</b><span class="mono">Coming</span></div></li>`;
    return `<li${here ? ' aria-current="page"' : ''}>${label}<div>${here ? `<b>${esc(p.title)}</b><span class="mono">You are here</span>` : `<a href="/${esc(p.path)}"><b>${esc(p.title)}</b></a><span class="mono">${esc(fmtDate(p.date))} · ${p.minutes} min</span>`}</div></li>`;
  }).join('')}${Array.from({ length: s.planned - s.parts.length }, (_, k) => `<li class="is-coming"><span class="mono">Part ${s.parts.length + k + 1}</span><div><b>To be announced</b></div></li>`).join('')}</ol>`;
}

function partBody(p) {
  const s = p.series;
  const live = s.parts.filter((x) => x.published);
  const i = live.indexOf(p);
  const prev = live[i - 1];
  const next = live[i + 1];
  const nextDraft = !next && s.parts.find((x) => x.n > p.n);
  return `    <article class="article">
      <header class="article-head wrap">
        <nav class="crumbs mono" aria-label="Breadcrumb"><a href="/writing/">Writing</a><span aria-hidden="true">/</span><a href="/writing/#build-notes">${SERIES_NAME}</a><span aria-hidden="true">/</span><a href="/${esc(s.path)}">${esc(s.title)}</a></nav>
        <span class="eyebrow">${esc(s.title)} · Part ${p.n} of ${s.planned}</span>
        <h1>${esc(p.title)}</h1>
        <p class="dek">${esc(p.description)}</p>
        <div class="article-meta mono"><span>${esc(fmtDate(p.date))}</span><span>${p.minutes} min read</span>${projectLinks(s)}</div>
      </header>
      <div class="wrap">${hero(p)}
        <div class="prose">
${p.html}
        </div>
        <aside class="series-box" aria-label="${esc(s.title)} series">
          <span class="eyebrow">${SERIES_NAME}</span>
          <h2><a href="/${esc(s.path)}">${esc(s.title)}</a></h2>
          ${partsList(s, p)}
          <p class="series-all mono"><a href="/writing/#build-notes">All ${SERIES_NAME.toLowerCase()} →</a></p>
        </aside>
        <nav class="pager" aria-label="More in this series">${prev ? `<a class="prev" href="/${esc(prev.path)}"><span class="mono">← Part ${prev.n}</span>${esc(prev.title)}</a>` : `<a class="prev" href="/${esc(s.path)}"><span class="mono">← Series</span>${esc(s.title)}</a>`}${next ? `<a class="next" href="/${esc(next.path)}"><span class="mono">Part ${next.n} →</span>${esc(next.title)}</a>` : nextDraft ? `<span class="next is-coming"><span class="mono">Part ${nextDraft.n} · coming</span>${esc(nextDraft.title)}</span>` : ''}</nav>
        <p class="article-foot mono">${p.linkedin ? `${extLink(p.linkedin, 'Discuss on LinkedIn')}` : ''}${s.repo ? extLink(s.repo, 'Read the code') : ''}</p>
      </div>
    </article>`;
}

