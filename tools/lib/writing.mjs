// Long-form writing: build-notes series and standalone essays, written as
// Markdown under content/writing/ and turned into static pages under writing/.
//
//   content/writing/<series>/_series.md     hub page of a build series -> writing/<series>/
//   content/writing/<series>/NN-<slug>.md   part NN of that series     -> writing/<series>/<slug>/
//   content/writing/essays/<slug>.md        a standalone essay         -> writing/<slug>/
//
// Only files with `status: published` become pages. Drafts stay in content/
// and show on a series hub as "coming" without a link.
import fs from 'node:fs';
import path from 'node:path';
import { parseFrontMatter, renderMarkdown } from './markdown.mjs';

export const SERIES_NAME = 'Build notes';
export const GENERATED = '<!-- Generated by tools/build_seo.mjs from content/writing/. Edit the Markdown, not this file. -->';

const esc = (s = '') => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const fmtDate = (iso) => new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
const isoDate = (d) => (d instanceof Date ? d.toISOString().slice(0, 10) : String(d || ''));
const minutes = (text) => Math.max(1, Math.round(text.split(/\s+/).length / 230));

function readPost(file, extra) {
  const { meta, body } = parseFrontMatter(fs.readFileSync(file, 'utf8'));
  for (const k of ['title', 'description', 'status']) if (!meta[k]) throw new Error(`${file}: missing "${k}" in front matter`);
  if (!['draft', 'published'].includes(meta.status)) throw new Error(`${file}: status must be draft or published`);
  if (meta.status === 'published' && !meta.date) throw new Error(`${file}: a published post needs a date`);
  const md = renderMarkdown(body);
  return { ...meta, ...extra, date: isoDate(meta.date), updated: isoDate(meta.updated || meta.date), tags: meta.tags || [], html: md.html, text: md.text, images: md.images, words: md.text.split(/\s+/).length, minutes: minutes(md.text), published: meta.status === 'published', file };
}

export function loadWriting(root) {
  const dir = path.join(root, 'content/writing');
  const series = [];
  const essays = [];
  if (!fs.existsSync(dir)) return { series, essays, pages: [] };
  for (const d of fs.readdirSync(dir, { withFileTypes: true }).filter((x) => x.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    const folder = path.join(dir, d.name);
    if (d.name === 'essays') {
      for (const f of fs.readdirSync(folder).filter((x) => x.endsWith('.md')).sort()) {
        const slug = f.replace(/\.md$/, '');
        essays.push(readPost(path.join(folder, f), { kind: 'essay', slug, path: `writing/${slug}/` }));
      }
      continue;
    }
    const hubFile = path.join(folder, '_series.md');
    if (!fs.existsSync(hubFile)) continue;
    const s = readPost(hubFile, { kind: 'series', slug: d.name, path: `writing/${d.name}/` });
    s.parts = fs.readdirSync(folder).filter((f) => /^\d+-.+\.md$/.test(f)).sort().map((f) => {
      const [, n, slug] = f.match(/^(\d+)-(.+)\.md$/);
      return readPost(path.join(folder, f), { kind: 'part', n: Number(n), slug, path: `writing/${d.name}/${slug}/`, series: s });
    });
    s.planned = Math.max(Number(s.parts_planned) || 0, s.parts.length);
    series.push(s);
  }
  essays.sort((a, b) => b.date.localeCompare(a.date));
  // `order` in a hub's front matter sets its place on /writing/ (lowest first); then newest first.
  series.sort((a, b) => (a.order ?? 99) - (b.order ?? 99) || b.date.localeCompare(a.date));
  const live = [...series.filter((s) => s.published), ...series.flatMap((s) => (s.published ? s.parts.filter((p) => p.published) : [])), ...essays.filter((e) => e.published)];
  return { series, essays, pages: live };
}

