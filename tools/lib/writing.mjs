/* ---------- Public API for build_seo.mjs ---------- */
export function writingPages(site, w) {
  const out = {};
  for (const p of w.pages) {
    const isSeries = p.kind === 'series';
    const modified = isSeries ? [p.updated, ...p.parts.filter((x) => x.published).map((x) => x.updated)].sort().at(-1) : p.updated;
    out[`${p.path}index.html`] = shell({
      site, page: p,
      title: p.kind === 'part' ? `${p.title} (${p.series.title}, part ${p.n})` : p.title,
      description: p.description,
      image: p.image, imageAlt: p.image_alt,
      type: isSeries ? 'website' : 'article',
      published: p.date, modified,
      jsonld: isSeries ? seriesLD(site, p) : articleLD(site, p),
      body: isSeries ? seriesBody(p, w) : p.kind === 'part' ? partBody(p) : essayBody(p, w),
    });
  }
  return out;
}

